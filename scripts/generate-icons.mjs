// Renders the app icons in public/ (website and PWA) and android/ (Android app)
// from the master artwork in assets/habit-icon.svg. Run `npm run icons` after
// changing the design.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const fromRoot = (file) => fileURLToPath(new URL(`../${file}`, import.meta.url));

const master = await readFile(fromRoot('assets/habit-icon.svg'), 'utf8');
const background = master.match(/<rect id="background"[^>]*fill="([^"]+)"/)?.[1];
const artwork = master.match(/<g id="artwork"[\s\S]*?<\/g>/)?.[0];
if (!background || !artwork) throw new Error('assets/habit-icon.svg needs #background and #artwork');

// One variant of the master: an optional rounded tile, the artwork scaled about
// the centre, and optionally heavier strokes so it survives tiny sizes.
function svg({ radius = 0, scale = 1, strokeWidth, transparent = false, monochrome = false }) {
  const offset = 256 * (1 - scale);
  let art = strokeWidth ? artwork.replace(/stroke-width="[\d.]+"/, `stroke-width="${strokeWidth}"`) : artwork;
  // Android themed icons use only the alpha channel: the ring stays solid and the
  // progress track (the artwork's first, unreached arc) becomes translucent.
  if (monochrome) {
    let first = true;
    art = art.replace(/stroke="#[0-9a-fA-F]{3,8}"/g, () => {
      const value = first ? 'stroke="#000" stroke-opacity="0.3"' : 'stroke="#000"';
      first = false;
      return value;
    });
  }
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">
  ${transparent ? '' : `<rect width="512" height="512" rx="${radius}" fill="${background}"/>`}
  <g transform="translate(${offset} ${offset}) scale(${scale})">
  ${art}
  </g>
</svg>
`;
}

const designs = {
  // Rounded tile for browsers, the macOS Dock and the Windows Start menu, which show the icon as-is.
  any: { svg: svg({ radius: 112 }), opaque: false },
  // Full bleed: Android crops it to the launcher's own shape (circle, squircle…).
  maskable: { svg: svg({ scale: 0.9 }), opaque: true },
  // Full bleed and opaque: iOS applies its own rounded mask.
  apple: { svg: svg({ scale: 0.94 }), opaque: true },
  // Larger artwork and heavier strokes read better at tab size.
  favicon: { svg: svg({ radius: 112, scale: 1.12, strokeWidth: 44 }), opaque: false },
  // Android adaptive icon layers (108 dp canvas; launchers show at most the central
  // 72 dp and guarantee only a 66 dp circle, so the artwork stays within ~55 dp).
  // The background layer is the colour in values/ic_launcher_background.xml.
  androidForeground: { svg: svg({ scale: 0.78, transparent: true }), opaque: false },
  androidMonochrome: { svg: svg({ scale: 0.78, transparent: true, monochrome: true }), opaque: false },
  // Legacy launcher icons for Android 7.x: a rounded tile and a circle.
  androidLegacy: { svg: svg({ radius: 96 }), opaque: false },
  androidRound: { svg: svg({ radius: 256 }), opaque: false },
};

const outputs = [
  { file: 'pwa-192x192.png', design: 'any', size: 192 },
  { file: 'pwa-512x512.png', design: 'any', size: 512 },
  { file: 'maskable-icon-512x512.png', design: 'maskable', size: 512 },
  { file: 'apple-touch-icon.png', design: 'apple', size: 180 },
  { file: 'favicon-32x32.png', design: 'favicon', size: 32 },
];

// Android launcher icons per screen density (1 dp = scale px).
const res = 'android/app/src/main/res';
const densities = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 };
for (const [density, scale] of Object.entries(densities)) {
  outputs.push(
    { file: `${res}/mipmap-${density}/ic_launcher.png`, design: 'androidLegacy', size: 48 * scale },
    { file: `${res}/mipmap-${density}/ic_launcher_round.png`, design: 'androidRound', size: 48 * scale },
    { file: `${res}/mipmap-${density}/ic_launcher_foreground.png`, design: 'androidForeground', size: 108 * scale },
    { file: `${res}/mipmap-${density}/ic_launcher_monochrome.png`, design: 'androidMonochrome', size: 108 * scale },
  );
}

for (const { file, design, size } of outputs) {
  const path = fromRoot(file.includes('/') ? file : `public/${file}`);
  let image = sharp(Buffer.from(designs[design].svg), { density: 384 }).resize(size, size);
  if (designs[design].opaque) image = image.flatten({ background });
  await mkdir(dirname(path), { recursive: true });
  await image.png({ compressionLevel: 9 }).toFile(path);
  const { width, height } = await sharp(path).metadata();
  console.log(`  ${file.includes('/') ? file : `public/${file}`}  ${width}×${height}`);
}
await writeFile(fromRoot('public/favicon.svg'), designs.favicon.svg);
console.log('  public/favicon.svg');
await writeFile(
  fromRoot(`${res}/values/ic_launcher_background.xml`),
  `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/generate-icons.mjs from assets/habit-icon.svg. -->\n<resources>\n    <color name="ic_launcher_background">${background}</color>\n</resources>\n`,
);
console.log(`  ${res}/values/ic_launcher_background.xml`);
